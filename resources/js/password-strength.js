import zxcvbn from 'zxcvbn';

const passwordMeterConfig = {
  class: ['empty', 'weak', 'moderate', 'strong', 'very-strong'],
  visibility: ['visible', 'hidden'],
  strengthMeterAttribute: 'data-add-strength-meter',
};

const getPasswordField = () => {
  const formSelector = `form[${passwordMeterConfig.strengthMeterAttribute}]`;
  const form = document.querySelector(formSelector);

  if (!form) {
    console.error(
      'Please configure the data-add-strength-meter attribute on your form. Pointing to the password field that meters the password strength.',
    );
    return null;
  }

  const passwordFieldName = form.getAttribute(passwordMeterConfig.strengthMeterAttribute);
  const passwordField = form.querySelector(`input[name="${passwordFieldName}"]`);
  if (!passwordField) {
    console.error('The data-add-strength-meter did not yield an input field with the name "' + passwordFieldName + '"');
    return null;
  }
  return passwordField;
};

const progressBar = document.querySelector('.progress-bar');
const strengthTextContainer = document.querySelector('.strength-text-container');
const strengthTexts = document.querySelectorAll('.strength-text');
const progressContainer = document.querySelector('.progress-container');
const helpTextContainer = document.querySelector('.help-text');

const hideAllStrengthTexts = () => {
  strengthTexts.forEach((strengthText) => {
    strengthText.classList.add(passwordMeterConfig.visibility[1]);
    strengthText.classList.remove(passwordMeterConfig.visibility[0]);
  });
};

const indicateStrength = (score) => {
  hideAllStrengthTexts();
  strengthTextContainer.classList.remove(passwordMeterConfig.visibility[1]);
  strengthTextContainer.classList.add(passwordMeterConfig.visibility[0]);

  // We start showing password strength from zxcvbn score 1 and upwards.
  // When showing the strength text, we need to subtract one from the score to
  // match the index in the strengthTexts array
  const textIndex = score - 1;
  if (textIndex >= 0) {
    strengthTexts[textIndex].classList.add(passwordMeterConfig.visibility[0]);
    strengthTexts[textIndex].classList.remove(passwordMeterConfig.visibility[1]);
  }
};

/**
 * Score is an integer value in a range 0 to 4 generated by zxcvbn
 * @param score
 */
const adjustStrengthMeter = (score) => {
  if (!Number.isInteger(score) || score < 0 || score > 4) {
    console.error('Invalid password score was calculated by zxcvbn. Score must be integer 0..4');
    return;
  }

  const percentage = score * 25;
  indicateStrength(score);
  progressContainer.classList.remove(passwordMeterConfig.visibility[1]);
  progressContainer.classList.add(passwordMeterConfig.visibility[0]);
  progressBar.style.width = `${percentage}%`;
  progressBar.setAttribute('class', passwordMeterConfig.class[score] + ' progress-bar');
};

const initializePasswordStrengthMeter = () => {
  const passwordField = getPasswordField();

  if (passwordField) {
    passwordField.addEventListener('input', () => {
      const result = zxcvbn(passwordField.value);
      if (passwordField.value.length < 12) {
        if (!strengthTextContainer.contains(helpTextContainer)) {
          strengthTextContainer.appendChild(helpTextContainer);
        }
      } else {
        if (strengthTextContainer.contains(helpTextContainer)) {
          strengthTextContainer.removeChild(helpTextContainer);
        }
      }
      const { score } = result;
      adjustStrengthMeter(score);
    });
  }
};

initializePasswordStrengthMeter();
